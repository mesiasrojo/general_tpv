use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};
use time::OffsetDateTime;

use crate::error::{DomainError, Result};
use crate::ids::{ProductId, SaleId, SaleLineId, Sku, StockMovementId, StockTransferId, StoreId};
use crate::money::Quantity;

/// Movements that explain every change of the on-hand quantity.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum StockMovementKind {
    /// Opening balance entered when the stock module starts being used.
    Initial,
    /// Goods received from a supplier.
    Purchase,
    /// Units taken out by a confirmed sale.
    Sale,
    /// Units returned by a customer.
    Return,
    /// Positive manual correction after a physical count.
    AdjustmentIn,
    /// Negative manual correction after a physical count or breakage.
    AdjustmentOut,
    /// Units sent to another store.
    TransferOut,
    /// Units received from another store.
    TransferIn,
}

impl StockMovementKind {
    /// Whether the movement may be entered by a user from the stock screen.
    /// Sales and returns are generated by the sales flow, never typed by hand.
    #[must_use]
    pub fn is_manual(self) -> bool {
        matches!(
            self,
            Self::Initial | Self::Purchase | Self::AdjustmentIn | Self::AdjustmentOut
        )
    }

    #[must_use]
    pub fn sign(self) -> i64 {
        match self {
            Self::Initial
            | Self::Purchase
            | Self::Return
            | Self::AdjustmentIn
            | Self::TransferIn => 1,
            Self::Sale | Self::AdjustmentOut | Self::TransferOut => -1,
        }
    }

    #[must_use]
    pub fn needs_reason(self) -> bool {
        matches!(self, Self::AdjustmentIn | Self::AdjustmentOut)
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StockMovement {
    pub id: StockMovementId,
    pub store_id: StoreId,
    pub product_id: ProductId,
    pub kind: StockMovementKind,
    /// Always a positive quantity. The sign is derived from `kind`.
    pub quantity: Quantity,
    pub reason: Option<String>,
    pub sale_id: Option<SaleId>,
    /// Makes sale movements idempotent: one stock movement per sale line.
    pub sale_line_id: Option<SaleLineId>,
    pub occurred_at: OffsetDateTime,
}

impl StockMovement {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        id: StockMovementId,
        store_id: StoreId,
        product_id: ProductId,
        kind: StockMovementKind,
        quantity: Quantity,
        reason: Option<String>,
        sale_id: Option<SaleId>,
        sale_line_id: Option<SaleLineId>,
        occurred_at: OffsetDateTime,
    ) -> Result<Self> {
        let reason = reason
            .map(|value| value.trim().to_string())
            .filter(|value| !value.is_empty());
        if kind.needs_reason() && reason.is_none() {
            return Err(DomainError::Validation(
                "stock adjustments require a reason".into(),
            ));
        }
        // Confirmed sales always reference their sale line. Invoice returns
        // reference the original sale but not a single line because the same
        // line can be partially returned across several rectificative invoices.
        // Transfers are linked through the stock_transfers document instead.
        let valid_reference = match kind {
            StockMovementKind::Sale => sale_id.is_some() && sale_line_id.is_some(),
            StockMovementKind::Return => sale_id.is_some(),
            _ => true,
        };
        if !valid_reference {
            return Err(DomainError::Validation(
                "sale movements must reference a sale line and returns must reference a sale"
                    .into(),
            ));
        }
        Ok(Self {
            id,
            store_id,
            product_id,
            kind,
            quantity,
            reason,
            sale_id,
            sale_line_id,
            occurred_at,
        })
    }

    #[must_use]
    pub fn signed_quantity(&self) -> Decimal {
        self.quantity.as_decimal() * Decimal::from(self.kind.sign())
    }
}

/// Document linking the outgoing and incoming movements of one transfer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StockTransfer {
    pub id: StockTransferId,
    pub from_store_id: StoreId,
    pub to_store_id: StoreId,
    pub product_id: ProductId,
    pub quantity: Quantity,
    pub reason: Option<String>,
    pub occurred_at: OffsetDateTime,
}

impl StockTransfer {
    pub fn new(
        id: StockTransferId,
        from_store_id: StoreId,
        to_store_id: StoreId,
        product_id: ProductId,
        quantity: Quantity,
        reason: Option<String>,
        occurred_at: OffsetDateTime,
    ) -> Result<Self> {
        if from_store_id == to_store_id {
            return Err(DomainError::Validation(
                "stock transfers require two different stores".into(),
            ));
        }
        let reason = reason
            .map(|value| value.trim().to_string())
            .filter(|value| !value.is_empty());
        if reason
            .as_ref()
            .is_some_and(|value| value.chars().count() > 200)
        {
            return Err(DomainError::Validation(
                "stock transfer reason is too long".into(),
            ));
        }
        Ok(Self {
            id,
            from_store_id,
            to_store_id,
            product_id,
            quantity,
            reason,
            occurred_at,
        })
    }
}

/// Current on-hand quantity for one product in one store.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StockLevel {
    pub store_id: StoreId,
    pub product_id: ProductId,
    pub sku: Sku,
    pub name: String,
    /// Can be negative when sales are confirmed above the recorded level.
    pub quantity: Decimal,
    /// Alert threshold. Zero disables the low-stock alert for the product.
    pub min_quantity: Decimal,
    pub updated_at: Option<OffsetDateTime>,
}

impl StockLevel {
    #[must_use]
    pub fn is_low(&self) -> bool {
        self.min_quantity > Decimal::ZERO && self.quantity <= self.min_quantity
    }

    /// Units needed to reach the configured minimum. Zero means no purchase
    /// suggestion, either because the level is healthy or the alert is off.
    #[must_use]
    pub fn restock_quantity(&self) -> Decimal {
        if self.min_quantity <= Decimal::ZERO {
            return Decimal::ZERO;
        }
        let missing = self.min_quantity - self.quantity;
        if missing > Decimal::ZERO {
            missing.normalize()
        } else {
            Decimal::ZERO
        }
    }

    pub fn set_minimum(&mut self, value: Decimal) -> Result<()> {
        if value < Decimal::ZERO {
            return Err(DomainError::Validation(
                "minimum stock cannot be negative".into(),
            ));
        }
        if value.scale() > 3 {
            return Err(DomainError::Validation(
                "minimum stock supports at most three decimals".into(),
            ));
        }
        self.min_quantity = value.normalize();
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ids::{ProductId, SaleId, SaleLineId, StoreId};

    fn movement(kind: StockMovementKind, quantity: Decimal) -> StockMovement {
        StockMovement::new(
            StockMovementId::new(),
            StoreId::new(),
            ProductId::new(),
            kind,
            Quantity::new(quantity).unwrap(),
            None,
            Some(SaleId::new()),
            Some(SaleLineId::new()),
            OffsetDateTime::now_utc(),
        )
        .unwrap()
    }

    #[test]
    fn movement_sign_follows_its_kind() {
        assert_eq!(
            movement(StockMovementKind::Purchase, Decimal::new(5, 0)).signed_quantity(),
            Decimal::new(5, 0)
        );
        assert_eq!(
            movement(StockMovementKind::Sale, Decimal::new(2, 0)).signed_quantity(),
            Decimal::new(-2, 0)
        );
        assert_eq!(
            movement(StockMovementKind::Return, Decimal::new(1, 0)).signed_quantity(),
            Decimal::new(1, 0)
        );
        assert_eq!(
            movement(StockMovementKind::TransferOut, Decimal::new(4, 0)).signed_quantity(),
            Decimal::new(-4, 0)
        );
        assert_eq!(
            movement(StockMovementKind::TransferIn, Decimal::new(4, 0)).signed_quantity(),
            Decimal::new(4, 0)
        );
    }

    #[test]
    fn transfers_require_two_stores_and_do_not_need_a_sale() {
        let from = StoreId::new();
        let to = StoreId::new();
        let product = ProductId::new();
        let transfer = StockTransfer::new(
            StockTransferId::new(),
            from,
            to,
            product,
            Quantity::new(Decimal::new(3, 0)).unwrap(),
            Some("  Reposición entre tiendas  ".into()),
            OffsetDateTime::now_utc(),
        )
        .unwrap();
        assert_eq!(transfer.reason.as_deref(), Some("Reposición entre tiendas"));

        let outgoing = StockMovement::new(
            StockMovementId::new(),
            from,
            product,
            StockMovementKind::TransferOut,
            Quantity::new(Decimal::new(3, 0)).unwrap(),
            Some("Transferencia a Tienda 2".into()),
            None,
            None,
            OffsetDateTime::now_utc(),
        );
        assert!(outgoing.is_ok());

        assert!(
            StockTransfer::new(
                StockTransferId::new(),
                from,
                from,
                product,
                Quantity::new(Decimal::ONE).unwrap(),
                None,
                OffsetDateTime::now_utc(),
            )
            .is_err()
        );
    }

    #[test]
    fn manual_movements_do_not_need_a_sale_reference() {
        let result = StockMovement::new(
            StockMovementId::new(),
            StoreId::new(),
            ProductId::new(),
            StockMovementKind::Purchase,
            Quantity::new(Decimal::new(3, 0)).unwrap(),
            None,
            None,
            None,
            OffsetDateTime::now_utc(),
        );
        assert!(result.is_ok());
    }

    #[test]
    fn invoice_returns_can_reference_only_the_original_sale() {
        let result = StockMovement::new(
            StockMovementId::new(),
            StoreId::new(),
            ProductId::new(),
            StockMovementKind::Return,
            Quantity::new(Decimal::new(5, 1)).unwrap(),
            Some("Devolución FAC-000001".into()),
            Some(SaleId::new()),
            None,
            OffsetDateTime::now_utc(),
        );
        assert!(result.is_ok());
    }

    #[test]
    fn adjustments_require_a_reason() {
        let result = StockMovement::new(
            StockMovementId::new(),
            StoreId::new(),
            ProductId::new(),
            StockMovementKind::AdjustmentOut,
            Quantity::new(Decimal::ONE).unwrap(),
            Some("   ".into()),
            None,
            None,
            OffsetDateTime::now_utc(),
        );
        assert!(result.is_err());
    }

    #[test]
    fn low_stock_requires_a_positive_threshold() {
        let mut level = StockLevel {
            store_id: StoreId::new(),
            product_id: ProductId::new(),
            sku: Sku::new("A-1").unwrap(),
            name: "Test".into(),
            quantity: Decimal::ZERO,
            min_quantity: Decimal::ZERO,
            updated_at: None,
        };
        assert!(!level.is_low());
        level.set_minimum(Decimal::new(2, 0)).unwrap();
        assert!(level.is_low());
        assert!(level.set_minimum(Decimal::new(-1, 0)).is_err());
    }

    #[test]
    fn restock_quantity_reaches_the_minimum_only_when_low() {
        let mut level = StockLevel {
            store_id: StoreId::new(),
            product_id: ProductId::new(),
            sku: Sku::new("A-1").unwrap(),
            name: "Test".into(),
            quantity: Decimal::new(15, 1),
            min_quantity: Decimal::new(4, 0),
            updated_at: None,
        };
        assert_eq!(level.restock_quantity(), Decimal::new(25, 1));
        level.quantity = Decimal::new(5, 0);
        assert_eq!(level.restock_quantity(), Decimal::ZERO);
        level.quantity = Decimal::new(-2, 0);
        assert_eq!(level.restock_quantity(), Decimal::new(6, 0));
        level.min_quantity = Decimal::ZERO;
        assert_eq!(level.restock_quantity(), Decimal::ZERO);
    }
}
